# 通用模式清洗函数
def clean_spoken_phrases(s: str) -> str:
    # 消除高频结巴与口语填充
    patterns = [
        (r"[，\s]*懂我意思吧[，？]?", "。"),
        (r"[，\s]*对吧[，？]?", "，"),
        (r"[，\s]*我只能说[，\s]*", "，"),
        (r"[，\s]*怎么说呢[，\s]*", "，"),
        (r"[，\s]*大家可以看[，\s]*", "，"),
        (r"[，\s]*大家可以想想[，\s]*", "，"),
        (r"[，\s]*大家知道吗[，\s]*", "，"),
        (r"[，\s]*我跟大家说[，\s]*", "，"),
        (r"[，\s]*我说实话[，\s]*", "，"),
        (r"[，\s]*这个这个[，\s]*", "，"),
        (r"[，\s]*很多这个[，\s]*", "，很多"),
        (r"[，\s]*反正[，\s]*", "，"),
        (r"[，\s]*好不好[，？]?", "。"),
        (r"[，\s]*那么等等[，\s]*", "等"),
        (r"[，\s]*哇塞[，\s]*", "，"),
        (r"[，\s]*其实其实[，\s]*", "其实"),
        (r"[，\s]*基本上基本[，\s]*", "基本"),
        (r"[，\s]*对对对[，\s]*", "，"),
        (r"[，\s]*然后然后[，\s]*", "然后"),
        (r"呃|啊|呢|嘛|喂[，\s]*", ""),
        (r"那个(?=[，。、])", ""),
        (r"就是说(?=[，。、])", ""),
    ]
    for pat, rep in patterns:
        s = re.sub(pat, rep, s)
    
    # 标点符号去重与规整
    s = re.sub(r"[，\s]{2,}", "，", s)
    s = re.sub(r"[。]{2,}", "。", s)
    s = re.sub(r"([。！？])，", r"\1", s)
    s = re.sub(r"，([。！？])", r"\1", s)
    s = re.sub(r"^[，\s]+", "", s)
    return s

